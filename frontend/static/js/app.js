(function () {
  "use strict";

  function $(id) {
    return document.getElementById(id);
  }

  function setResult(node, text, isError) {
    node.textContent = "";
    node.classList.toggle("is-error", Boolean(isError));
    var body = document.createElement("div");
    body.textContent = text;
    node.appendChild(body);
    return node;
  }

  // Models reply in Markdown with occasional LaTeX. The helpers below turn the
  // common subset into real elements. Every piece of model output is written
  // through textContent, so nothing it returns can become markup.

  var MATH_SYMBOLS = [
    [/\^\\circ/g, "°"],
    [/\\circ/g, "°"],
    [/\\times/g, "×"],
    [/\\div/g, "÷"],
    [/\\pm/g, "±"],
    [/\\cdot/g, "·"],
    [/\\leq\b/g, "≤"],
    [/\\geq\b/g, "≥"],
    [/\\neq\b/g, "≠"],
    [/\^2\b/g, "²"],
    [/\^3\b/g, "³"]
  ];

  function tidyMath(text) {
    // Unwrap $...$ only when the content looks like maths, so prices survive.
    var out = String(text == null ? "" : text).replace(/\$([^$\n]+)\$/g, function (match, inner) {
      return /[\\^_{}]/.test(inner) ? inner : match;
    });
    MATH_SYMBOLS.forEach(function (rule) {
      out = out.replace(rule[0], rule[1]);
    });
    return out;
  }

  var INLINE = /\*\*([\s\S]+?)\*\*|`([^`\n]+?)`|\*(\S[^*\n]*?)\*/g;

  function appendInline(parent, text) {
    var last = 0;
    var match;
    INLINE.lastIndex = 0;
    while ((match = INLINE.exec(text)) !== null) {
      if (match.index > last) {
        parent.appendChild(document.createTextNode(text.slice(last, match.index)));
      }
      var el;
      if (match[1] !== undefined) {
        el = document.createElement("strong");
        el.textContent = match[1];
      } else if (match[2] !== undefined) {
        el = document.createElement("code");
        el.textContent = match[2];
      } else {
        el = document.createElement("em");
        el.textContent = match[3];
      }
      parent.appendChild(el);
      last = INLINE.lastIndex;
    }
    if (last < text.length) {
      parent.appendChild(document.createTextNode(text.slice(last)));
    }
  }

  var RULE = /^(-{3,}|\*{3,}|_{3,})$/;
  var HEADING = /^(#{1,6})\s+(.*)$/;
  var QUOTE = /^>\s?(.*)$/;
  var BULLET = /^[-*+]\s+(.*)$/;
  var NUMBERED = /^(\d+)[.)]\s+(.*)$/;

  function startsBlock(line) {
    return !line || RULE.test(line) || HEADING.test(line) || QUOTE.test(line) ||
      BULLET.test(line) || NUMBERED.test(line);
  }

  function renderMarkdown(container, raw) {
    var lines = tidyMath(raw).split(/\r?\n/);
    var index = 0;
    var list = null;

    function closeList() {
      if (list) {
        container.appendChild(list);
        list = null;
      }
    }

    while (index < lines.length) {
      var line = lines[index].trim();

      if (!line) {
        closeList();
        index += 1;
        continue;
      }

      if (RULE.test(line)) {
        closeList();
        container.appendChild(document.createElement("hr"));
        index += 1;
        continue;
      }

      var heading = HEADING.exec(line);
      if (heading) {
        closeList();
        // Offset by two: the page already owns h1 and h2.
        var title = document.createElement("h" + Math.min(heading[1].length + 2, 6));
        appendInline(title, heading[2]);
        container.appendChild(title);
        index += 1;
        continue;
      }

      var quote = QUOTE.exec(line);
      if (quote) {
        closeList();
        var block = document.createElement("blockquote");
        appendInline(block, quote[1]);
        container.appendChild(block);
        index += 1;
        continue;
      }

      var bullet = BULLET.exec(line);
      var numbered = NUMBERED.exec(line);
      if (bullet || numbered) {
        var wanted = bullet ? "ul" : "ol";
        if (!list || list.nodeName.toLowerCase() !== wanted) {
          closeList();
          list = document.createElement(wanted);
        }
        var item = document.createElement("li");
        appendInline(item, bullet ? bullet[1] : numbered[2]);
        list.appendChild(item);
        index += 1;
        continue;
      }

      closeList();
      var paragraph = [];
      while (index < lines.length && !startsBlock(lines[index].trim())) {
        paragraph.push(lines[index].trim());
        index += 1;
      }
      var text = document.createElement("p");
      appendInline(text, paragraph.join(" "));
      container.appendChild(text);
    }

    closeList();
  }

  function setMarkdown(node, text) {
    node.textContent = "";
    node.classList.remove("is-error");
    var body = document.createElement("div");
    body.className = "markdown";
    renderMarkdown(body, text);
    node.appendChild(body);
    return node;
  }

  function addMeta(node, model) {
    if (!model) return;
    var meta = document.createElement("div");
    meta.className = "meta";
    meta.textContent = "Generated by: " + model;
    node.appendChild(meta);
  }

  function errorMessage(payload, fallback) {
    if (!payload) return fallback;
    var detail = payload.detail;
    if (typeof detail === "string") return detail;
    if (Array.isArray(detail) && detail.length && detail[0].msg) return detail[0].msg;
    return fallback;
  }

  async function callApi(path, body) {
    var response = await fetch(path, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify(body)
    });
    var payload = null;
    try {
      payload = await response.json();
    } catch (err) {
      payload = null;
    }
    if (!response.ok) {
      throw new Error(errorMessage(payload, "Request failed (" + response.status + ")"));
    }
    return payload;
  }

  function wireForm(formId, resultId, buildBody, render) {
    var form = $(formId);
    var result = $(resultId);
    if (!form) return;

    form.addEventListener("submit", async function (event) {
      event.preventDefault();
      var button = form.querySelector("button[type=submit]");
      var body;
      try {
        body = buildBody(form);
      } catch (err) {
        setResult(result, err.message, true);
        return;
      }

      button.disabled = true;
      setResult(result, "Working on it…", false);
      try {
        var data = await callApi(form.dataset.endpoint, body);
        render(result, data);
      } catch (err) {
        setResult(result, err.message, true);
      } finally {
        button.disabled = false;
      }
    });
  }

  function requireValue(form, name, label) {
    var value = (form.elements[name].value || "").trim();
    if (!value) throw new Error(label + " is required.");
    return value;
  }

  function renderText(field) {
    return function (node, data) {
      setMarkdown(node, data[field]);
      addMeta(node, data.model_used);
    };
  }

  function renderQuiz(node, data) {
    node.textContent = "";
    node.classList.remove("is-error");

    data.questions.forEach(function (item, index) {
      var block = document.createElement("div");
      block.className = "quiz-item";

      var question = document.createElement("p");
      question.appendChild(document.createTextNode(index + 1 + ". "));
      appendInline(question, tidyMath(item.question));
      block.appendChild(question);

      var feedback = document.createElement("div");
      feedback.className = "feedback";

      item.options.forEach(function (option) {
        var choice = document.createElement("button");
        choice.type = "button";
        choice.className = "option";
        // Kept as plain text: the correction below matches an option's
        // textContent against correct_answer, which formatting would break.
        choice.textContent = option;
        choice.addEventListener("click", function () {
          var correct = option === item.correct_answer;
          choice.classList.add(correct ? "correct" : "incorrect");
          if (correct) {
            feedback.textContent = "Correct.";
          } else {
            feedback.textContent = "Not quite. Correct answer: " + item.correct_answer;
            Array.prototype.forEach.call(block.querySelectorAll(".option"), function (btn) {
              if (btn.textContent === item.correct_answer) btn.classList.add("correct");
            });
          }
        });
        block.appendChild(choice);
      });

      block.appendChild(feedback);
      node.appendChild(block);
    });

    addMeta(node, data.model_used);
  }

  function renderHistory(node, records) {
    node.textContent = "";
    node.classList.remove("is-error");

    if (!records.length) {
      setResult(node, "No activity recorded yet.", false);
      return;
    }

    records.forEach(function (record) {
      var item = document.createElement("div");
      item.className = "history-item";

      var tag = document.createElement("span");
      tag.className = "tag";
      tag.textContent = record.query_type;
      item.appendChild(tag);

      var title = document.createElement("span");
      title.textContent = record.query_text.slice(0, 110);
      item.appendChild(title);

      var meta = document.createElement("div");
      meta.className = "meta";
      meta.textContent =
        new Date(record.created_at).toLocaleString() +
        (record.model_used ? " · " + record.model_used : "");
      item.appendChild(meta);

      node.appendChild(item);
    });
  }

  function setupTabs() {
    var tabs = document.querySelectorAll(".tab");
    Array.prototype.forEach.call(tabs, function (tab) {
      tab.addEventListener("click", function () {
        Array.prototype.forEach.call(tabs, function (other) {
          other.classList.toggle("is-active", other === tab);
        });
        Array.prototype.forEach.call(document.querySelectorAll(".panel"), function (panel) {
          panel.classList.toggle("is-active", panel.id === "panel-" + tab.dataset.tab);
        });
        if (tab.dataset.tab === "history") loadHistory();
      });
    });
  }

  async function loadHistory() {
    var node = $("result-history");
    setResult(node, "Loading…", false);
    try {
      var response = await fetch("/history?limit=20");
      if (!response.ok) throw new Error("Could not load history.");
      renderHistory(node, await response.json());
    } catch (err) {
      setResult(node, err.message, true);
    }
  }

  document.addEventListener("DOMContentLoaded", function () {
    setupTabs();

    $("form-qa").dataset.endpoint = "/qa";
    $("form-explain").dataset.endpoint = "/explain";
    $("form-quiz").dataset.endpoint = "/quiz";
    $("form-summary").dataset.endpoint = "/summarize";
    $("form-path").dataset.endpoint = "/learn/recommendations";

    wireForm(
      "form-qa",
      "result-qa",
      function (form) {
        return {
          question: requireValue(form, "question", "Question"),
          context: (form.elements.context.value || "").trim() || null
        };
      },
      renderText("answer")
    );

    wireForm(
      "form-explain",
      "result-explain",
      function (form) {
        return {
          topic: requireValue(form, "topic", "Topic"),
          audience: form.elements.audience.value
        };
      },
      renderText("explanation")
    );

    wireForm(
      "form-quiz",
      "result-quiz",
      function (form) {
        return {
          passage: requireValue(form, "passage", "Passage"),
          num_questions: Number(form.elements.num_questions.value) || 3
        };
      },
      renderQuiz
    );

    wireForm(
      "form-summary",
      "result-summary",
      function (form) {
        return {
          text: requireValue(form, "text", "Content"),
          max_sentences: Number(form.elements.max_sentences.value) || 3
        };
      },
      renderText("summary")
    );

    wireForm(
      "form-path",
      "result-path",
      function (form) {
        return {
          topic: requireValue(form, "topic", "Topic"),
          level: form.elements.level.value
        };
      },
      renderText("learning_path")
    );

    $("history-refresh").addEventListener("click", loadHistory);
  });
})();
