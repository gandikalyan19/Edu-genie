(function () {
  "use strict";

  function $(id) {
    return document.getElementById(id);
  }

  function setResult(node, text, isError) {
    node.textContent = "";
    node.classList.toggle("is-error", Boolean(isError));
    var body = document.createElement("div");
    body.textContent = text;
    node.appendChild(body);
    return node;
  }

  function addMeta(node, model) {
    if (!model) return;
    var meta = document.createElement("div");
    meta.className = "meta";
    meta.textContent = "Generated by: " + model;
    node.appendChild(meta);
  }

  function errorMessage(payload, fallback) {
    if (!payload) return fallback;
    var detail = payload.detail;
    if (typeof detail === "string") return detail;
    if (Array.isArray(detail) && detail.length && detail[0].msg) return detail[0].msg;
    return fallback;
  }

  async function callApi(path, body) {
    var response = await fetch(path, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify(body)
    });
    var payload = null;
    try {
      payload = await response.json();
    } catch (err) {
      payload = null;
    }
    if (!response.ok) {
      throw new Error(errorMessage(payload, "Request failed (" + response.status + ")"));
    }
    return payload;
  }

  function wireForm(formId, resultId, buildBody, render) {
    var form = $(formId);
    var result = $(resultId);
    if (!form) return;

    form.addEventListener("submit", async function (event) {
      event.preventDefault();
      var button = form.querySelector("button[type=submit]");
      var body;
      try {
        body = buildBody(form);
      } catch (err) {
        setResult(result, err.message, true);
        return;
      }

      button.disabled = true;
      setResult(result, "Working on it…", false);
      try {
        var data = await callApi(form.dataset.endpoint, body);
        render(result, data);
      } catch (err) {
        setResult(result, err.message, true);
      } finally {
        button.disabled = false;
      }
    });
  }

  function requireValue(form, name, label) {
    var value = (form.elements[name].value || "").trim();
    if (!value) throw new Error(label + " is required.");
    return value;
  }

  function renderText(field) {
    return function (node, data) {
      setResult(node, data[field], false);
      addMeta(node, data.model_used);
    };
  }

  function renderQuiz(node, data) {
    node.textContent = "";
    node.classList.remove("is-error");

    data.questions.forEach(function (item, index) {
      var block = document.createElement("div");
      block.className = "quiz-item";

      var question = document.createElement("p");
      question.textContent = index + 1 + ". " + item.question;
      block.appendChild(question);

      var feedback = document.createElement("div");
      feedback.className = "feedback";

      item.options.forEach(function (option) {
        var choice = document.createElement("button");
        choice.type = "button";
        choice.className = "option";
        choice.textContent = option;
        choice.addEventListener("click", function () {
          var correct = option === item.correct_answer;
          choice.classList.add(correct ? "correct" : "incorrect");
          if (correct) {
            feedback.textContent = "Correct.";
          } else {
            feedback.textContent = "Not quite. Correct answer: " + item.correct_answer;
            Array.prototype.forEach.call(block.querySelectorAll(".option"), function (btn) {
              if (btn.textContent === item.correct_answer) btn.classList.add("correct");
            });
          }
        });
        block.appendChild(choice);
      });

      block.appendChild(feedback);
      node.appendChild(block);
    });

    addMeta(node, data.model_used);
  }

  function renderHistory(node, records) {
    node.textContent = "";
    node.classList.remove("is-error");

    if (!records.length) {
      setResult(node, "No activity recorded yet.", false);
      return;
    }

    records.forEach(function (record) {
      var item = document.createElement("div");
      item.className = "history-item";

      var tag = document.createElement("span");
      tag.className = "tag";
      tag.textContent = record.query_type;
      item.appendChild(tag);

      var title = document.createElement("span");
      title.textContent = record.query_text.slice(0, 110);
      item.appendChild(title);

      var meta = document.createElement("div");
      meta.className = "meta";
      meta.textContent =
        new Date(record.created_at).toLocaleString() +
        (record.model_used ? " · " + record.model_used : "");
      item.appendChild(meta);

      node.appendChild(item);
    });
  }

  function setupTabs() {
    var tabs = document.querySelectorAll(".tab");
    Array.prototype.forEach.call(tabs, function (tab) {
      tab.addEventListener("click", function () {
        Array.prototype.forEach.call(tabs, function (other) {
          other.classList.toggle("is-active", other === tab);
        });
        Array.prototype.forEach.call(document.querySelectorAll(".panel"), function (panel) {
          panel.classList.toggle("is-active", panel.id === "panel-" + tab.dataset.tab);
        });
        if (tab.dataset.tab === "history") loadHistory();
      });
    });
  }

  async function loadHistory() {
    var node = $("result-history");
    setResult(node, "Loading…", false);
    try {
      var response = await fetch("/history?limit=20");
      if (!response.ok) throw new Error("Could not load history.");
      renderHistory(node, await response.json());
    } catch (err) {
      setResult(node, err.message, true);
    }
  }

  document.addEventListener("DOMContentLoaded", function () {
    setupTabs();

    $("form-qa").dataset.endpoint = "/qa";
    $("form-explain").dataset.endpoint = "/explain";
    $("form-quiz").dataset.endpoint = "/quiz";
    $("form-summary").dataset.endpoint = "/summarize";
    $("form-path").dataset.endpoint = "/learn/recommendations";

    wireForm(
      "form-qa",
      "result-qa",
      function (form) {
        return {
          question: requireValue(form, "question", "Question"),
          context: (form.elements.context.value || "").trim() || null
        };
      },
      renderText("answer")
    );

    wireForm(
      "form-explain",
      "result-explain",
      function (form) {
        return {
          topic: requireValue(form, "topic", "Topic"),
          audience: form.elements.audience.value
        };
      },
      renderText("explanation")
    );

    wireForm(
      "form-quiz",
      "result-quiz",
      function (form) {
        return {
          passage: requireValue(form, "passage", "Passage"),
          num_questions: Number(form.elements.num_questions.value) || 3
        };
      },
      renderQuiz
    );

    wireForm(
      "form-summary",
      "result-summary",
      function (form) {
        return {
          text: requireValue(form, "text", "Content"),
          max_sentences: Number(form.elements.max_sentences.value) || 3
        };
      },
      renderText("summary")
    );

    wireForm(
      "form-path",
      "result-path",
      function (form) {
        return {
          topic: requireValue(form, "topic", "Topic"),
          level: form.elements.level.value
        };
      },
      renderText("learning_path")
    );

    $("history-refresh").addEventListener("click", loadHistory);
  });
})();
